const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
  const browser=await chromium.launch();
  const context=await browser.newContext({acceptDownloads:true});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const id='browser_'+crypto.randomBytes(5).toString('hex'), password=crypto.randomBytes(16).toString('hex');
  const base='http://127.0.0.1:8081';
  async function login(p,kind,username,pw,remember=false){
    await p.locator('#loginButton').click();
    await p.locator('#loginForm select').selectOption(kind);
    await p.locator('#loginForm [name=username]').fill(username);
    await p.locator('#loginForm [name=password]').fill(pw);
    if(remember)await p.locator('[name=remember]').check();
    await p.locator('#loginForm button[type=submit]').click();
    await p.locator('#workspaceView').waitFor({state:'visible'});
    await p.locator('#panel .panel-title').waitFor();
  }
  try{
    await page.goto(base);
    await page.locator('#registerButton').click();
    await page.locator('[name=full_name]').fill('브라우저고객');
    await page.locator('[name=login_id]').fill(id);
    assert.equal(await page.locator('[name=email]').count(),0);
    await page.locator('[name=rrn]').fill('TEST-RRN-123456');
    await page.locator('#registerForm [name=password]').fill(password);
    await page.locator('#registerForm button[type=submit]').click();
    await page.locator('#loginForm').waitFor();
    await page.locator('#loginForm [name=username]').fill(id);
    await page.locator('#loginForm [name=password]').fill(password);
    await page.locator('[name=remember]').check();
    await page.locator('#loginForm button[type=submit]').click();
    await page.locator('#panel [data-action=open]').click();
    await page.locator('#accountForm [name=pin]').fill('6184');
    await page.locator('#accountForm [name=confirm]').fill('6184');
    await page.locator('#accountForm button[type=submit]').click();
    await page.locator('[data-pin]').waitFor();
    assert.match(await page.locator('#panel').innerText(),/정상/);
    await page.locator('[data-pin]').click();
    await page.locator('#pinForm [name=pin]').fill('6184');
    await page.locator('#pinForm button[type=submit]').click();
    await page.locator('#modal').waitFor({state:'hidden'});
    await page.reload();await page.locator('[data-pin]').waitFor();
    await page.locator('#sideMenu [data-view=profile]').click();
    await page.getByText('브라우저고객',{exact:true}).waitFor();
    await page.screenshot({path:'test-results/customer.png',fullPage:true});
    await page.locator('#loginButton').click();
    await page.locator('#homeView').waitFor({state:'visible'});
    await login(page,'staff',process.env.SMOKE_STAFF_ID,process.env.SMOKE_STAFF_PASSWORD);
    await page.locator('#customerSearch').fill(id);
    await page.locator('[data-customer]').click();
    await page.getByText('끝 4자리 3456',{exact:true}).waitFor();
    assert.match(await page.locator('#modalBody').innerText(),/보유 계좌 1개/);
    await page.locator('#closeModal').click();
    await page.locator('#sideMenu [data-view=staff]').click();
    await page.locator('[data-action=addStaff]').click();
    const employee='ui_'+crypto.randomBytes(5).toString('hex');
    await page.locator('[name=display_name]').fill('추가직원');
    await page.locator('[name=employee_id]').fill(employee);
    await page.locator('#registerForm [name=password]').fill(password);
    await page.locator('#registerForm button[type=submit]').click();
    const row=page.locator('tr').filter({hasText:employee});await row.waitFor();
    const otherContext=await browser.newContext();const other=await otherContext.newPage();
    await other.goto(base);await login(other,'staff',employee,password);
    page.once('dialog',d=>d.accept());await row.locator('[data-toggle]').click();
    await row.getByText('비활성',{exact:true}).waitFor();
    await other.reload();await other.locator('#homeView').waitFor({state:'visible'});
    assert.equal(await other.locator('#loginButton').innerText(),'로그인 ↗');
    await page.locator('#sideMenu [data-view=events]').click();
    const download=page.waitForEvent('download');await page.locator('[data-action=export]').click();
    const file=await download;await file.saveAs('test-results/audit.jsonl');
    const lines=fs.readFileSync('test-results/audit.jsonl','utf8').trim().split('\n');
    assert.ok(lines.length>0);assert.ok(lines.every(s=>JSON.parse(s).http_status));
    await page.screenshot({path:'test-results/staff-audit.png',fullPage:true});
    await page.locator('#sideMenu [data-view=lab]').click();
    await page.getByText('수정 모드 · 권한 검사 적용',{exact:true}).waitFor();
    assert.deepEqual(errors,[]);
    console.log('PASS: Chromium customer signup/login/reload/account/PIN and staff detail/create/disable/audit download');
    await otherContext.close();
  }catch(e){await page.screenshot({path:'test-results/browser-failure.png',fullPage:true});throw e}
  finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
